#!/usr/bin/env node
/**
 * Generate the diagrams referenced by docs/ into docs/assets/.
 *
 * Layout lives here rather than in the SVGs. Every arrow endpoint is derived
 * from a box edge, so editing coordinates in the output silently detaches the
 * arrows from the boxes they point at. Change this file, then re-run it.
 *
 * Each diagram ships as a zh and an en variant: the geometry is shared, the
 * copy is not, and English runs wider -- hence the per-locale box widths.
 *
 *   npm run docs:assets
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
// One folder for both locales, matching the -zh/-en pairs README.md and
// README_zh.md already pull from here. Keeping them together is what lets a
// page under docs/en/ reach them as ../assets/ -- the same path that works
// when that file is read on GitHub, where docs/en/assets/ would not exist.
const OUT_DIR = path.resolve(here, "..", "docs", "assets");

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;");

// English copy needs a Latin-first stack: on Windows the CJK faces listed for
// the zh variant win the glyph match, so every English label would render in
// Microsoft YaHei -- which also measures wider than the layout allows.
const FONT_SANS = {
	zh: '"PingFang SC","Microsoft YaHei","Noto Sans SC","Hiragino Sans GB","Segoe UI",sans-serif',
	en: '"Segoe UI",system-ui,-apple-system,"Helvetica Neue",Arial,sans-serif',
};
const FONT_MONO = {
	zh: 'Consolas,Menlo,"PingFang SC","Microsoft YaHei","Noto Sans SC",monospace',
	en: 'Consolas,"Cascadia Mono",Menlo,"DejaVu Sans Mono",monospace',
};

function style(lang) {
	return `  <style>
    .layer{ font-family:${FONT_SANS[lang]}; }
    .mono { font-family:${FONT_MONO[lang]}; }
    .flow { font-family:${FONT_MONO[lang]}; font-size:16px; font-weight:700; fill:#0f3d91; letter-spacing:.4px; }
    .node { font-family:${FONT_MONO[lang]}; font-size:15px; font-weight:700; fill:#0f3d91; }
    .sub  { font-size:13.5px; fill:#5b6472; }
    .state{ font-family:${FONT_MONO[lang]}; font-size:12.5px; fill:#79818f; }
    .card { fill:#ffffff; stroke:#d6dbe6; stroke-width:1.5; }
    .main { fill:#f7f9ff; stroke:#4263d6; stroke-width:2; }
    .edge { stroke:#8a94a6; stroke-width:1.9; fill:none; }
    .dash { stroke:#8a94a6; stroke-width:1.9; fill:none; stroke-dasharray:7 6; }
    .lbl  { fill:#79818f; font-size:13px; }
  </style>`;
}

const DEFS = `  <defs>
    <marker id="arw" viewBox="0 0 10 10" refX="8.5" refY="5" markerWidth="7" markerHeight="7" orient="auto">
      <path d="M0,0 L10,5 L0,10 Z" fill="#8a94a6"/>
    </marker>
  </defs>`;

/** Collects the body and fails loudly rather than writing a diagram with detached arrows. */
function emit({ file, lang, label, minX = 0, minY = 0, w, h, body, checks = [] }) {
	const failed = checks.filter(([ok, msg]) => !ok).map(([, msg]) => msg);
	if (failed.length) {
		console.error(`layout check failed for ${file}:`);
		for (const f of failed) console.error("  -", f);
		process.exit(1);
	}
	const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${minX} ${minY} ${w} ${h}" width="${w}" height="${h}"
     role="img" aria-label="${esc(label)}">
  <title>${esc(label)}</title>
  <!-- Generated by scripts/build-docs-svgs.mjs. Change the layout there, not the coordinates here. -->
${style(lang)}
${DEFS}
${body}</svg>
`;
	fs.writeFileSync(path.join(OUT_DIR, file), svg);
	return `${file}  ${w}x${h}`;
}

