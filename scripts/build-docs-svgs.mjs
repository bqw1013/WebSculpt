// ── 1. System architecture ───────────────────────────────────────────────────
// docs/Architecture.md, section 1. Two columns drive everything: boxes are
// centred on the column centres and arrows run column-centre to column-centre.
function architecture(lang) {
	const t = ARCH_TEXT[lang];
	const COL_L = 152; // explore / node
	const COL_R = 440; // capture -> command -> CLI / browser
	const COL_SHELL = 620;
	const COL_AGENT = 370;
	const MAIN_H = 76;
	const CARD_H = 50;
	const ROW_GAP = 46;
	const CARD_GAP = 56;

	const boxes = [
		{ id: "agent", cx: COL_AGENT, y: 40, w: 640, h: MAIN_H, cls: "main", title: "AI Agent", sub: t.sub.agent },
		{ id: "explore", cx: COL_L, w: t.boxW.explore, h: MAIN_H, cls: "main", title: "explore", sub: t.sub.explore },
		{ id: "capture", cx: COL_R, w: t.boxW.capture, h: MAIN_H, cls: "main", title: "capture", sub: t.sub.capture },
		{ id: "command", cx: COL_R, w: t.boxW.command, h: MAIN_H, cls: "main", title: "command", sub: t.sub.command },
		{ id: "cli", cx: COL_R, w: t.boxW.cli, h: MAIN_H, cls: "main", title: "CLI", sub: t.sub.cli },
		{ id: "node", cx: COL_L, w: 110, h: CARD_H, cls: "card", title: "node", sub: null },
		{ id: "browser", cx: COL_R, w: 130, h: CARD_H, cls: "card", title: "browser", sub: "(daemon)" },
		{ id: "shell", cx: COL_SHELL, w: 120, h: CARD_H, cls: "card", title: "shell / py", sub: null },
	];

	const row1 = boxes[0].y + MAIN_H + ROW_GAP;
	const row2 = row1 + MAIN_H + ROW_GAP;
	const row3 = row2 + MAIN_H + ROW_GAP;
	const row4 = row3 + MAIN_H + CARD_GAP;
	const ROW_Y = { explore: row1, capture: row1, command: row2, cli: row3, node: row4, browser: row4, shell: row4 };
	for (const b of boxes) {
		if (ROW_Y[b.id] !== undefined) b.y = ROW_Y[b.id];
		b.x = b.cx - b.w / 2;
	}

	const B = Object.fromEntries(
		boxes.map((b) => [b.id, { L: b.x, R: b.x + b.w, T: b.y, B: b.y + b.h, Cx: b.x + b.w / 2, Cy: b.y + b.h / 2 }]),
	);
	const forkY = B.cli.B + CARD_GAP / 2;

	const edges = [
		{ d: `M${COL_L},${B.agent.B} V${B.explore.T}`, arrow: true },
		{ d: `M${COL_R},${B.agent.B} V${B.capture.T}`, arrow: true },
		{ d: `M${B.explore.R},${B.explore.Cy} H${B.capture.L}`, arrow: true },
		{ d: `M${COL_R},${B.capture.B} V${B.command.T}`, arrow: true },
		{ d: `M${COL_R},${B.command.B} V${B.cli.T}`, arrow: true },
		{ d: `M${COL_R},${B.cli.B} V${forkY}`, arrow: false },
		{ d: `M${COL_L},${forkY} H${COL_SHELL}`, arrow: false },
		{ d: `M${COL_L},${forkY} V${B.node.T}`, arrow: true },
		{ d: `M${COL_R},${forkY} V${B.browser.T}`, arrow: true },
		{ d: `M${COL_SHELL},${forkY} V${B.shell.T}`, arrow: true },
		// Reuse path: off command's left edge, across the empty left column, up into explore.
		{ d: `M${B.command.L},${B.command.Cy} H${COL_L} V${B.explore.B}`, arrow: true, dash: true },
	];

	let body = "  <!-- main chain, three-way dispatch, reuse loop -->\n";
	for (const e of edges) {
		body += `  <path class="${e.dash ? "dash" : "edge"}" d="${e.d}"${e.arrow ? ' marker-end="url(#arw)"' : ""}/>\n`;
	}
	body += `  <text class="lbl layer" x="${(B.explore.R + B.capture.L) / 2}" y="${B.explore.Cy - 9}" text-anchor="middle">${esc(t.edge.handoff)}</text>\n`;
	body += `  <text class="lbl layer" x="${(B.command.L + COL_L) / 2}" y="${B.command.Cy - 9}" text-anchor="middle">${esc(t.edge.reuse)}</text>\n`;
	body += "  <!-- boxes -->\n";
	for (const b of boxes) {
		const cx = b.x + b.w / 2;
		body += `  <rect class="${b.cls}" x="${b.x}" y="${b.y}" width="${b.w}" height="${b.h}" rx="8"/>\n`;
		if (b.sub) {
			body += `  <text class="mono flow" x="${cx}" y="${b.y + b.h / 2 - 4}" text-anchor="middle">${esc(b.title)}</text>\n`;
			body += `  <text class="${b.cls === "card" ? "mono" : "layer"} sub" x="${cx}" y="${b.y + b.h / 2 + 20}" text-anchor="middle">${esc(b.sub)}</text>\n`;
		} else {
			body += `  <text class="mono flow" x="${cx}" y="${b.y + b.h / 2 + 6}" text-anchor="middle">${esc(b.title)}</text>\n`;
		}
	}

	const PAD = 40;
	const minX = Math.min(...boxes.map((b) => b.x)) - PAD;
	const minY = Math.min(...boxes.map((b) => b.y)) - PAD;
	const w = Math.max(...boxes.map((b) => b.x + b.w)) + PAD - minX;
	const h = Math.max(...boxes.map((b) => b.y + b.h)) + PAD - minY;

	return emit({
		file: t.file,
		lang,
		label: t.label,
		minX,
		minY,
		w,
		h,
		body,
		checks: [
			[B.explore.T === B.capture.T, "explore and capture are not level"],
			[B.explore.R < B.capture.L, "explore overlaps capture (no room for the handoff label)"],
			[B.command.Cx === COL_R && B.cli.Cx === COL_R, "command/CLI drifted off the right column"],
			[B.command.B < B.cli.T, "command overlaps CLI"],
			[B.cli.B < B.node.T, "CLI overlaps the backend row"],
			[B.command.L > COL_L, "reuse label has no horizontal room"],
			[COL_L < B.explore.R && COL_R > B.capture.L, "column centre fell outside its own box"],
		],
	});
}

// ── 2. Six-artifact pipeline ─────────────────────────────────────────────────
// docs/Capture.md, section 3.1. A straight chain: each box gates the next, so
// the arrow between two boxes always spans exactly that pair's gap.
function artifactPipeline(lang) {
	const NODES = [
		["evidence", "done"],
		["command", "ready / done / blocked"],
		["manifest", "ready / done / blocked"],
		["readme", "ready / done / blocked"],
		["context", "ready / done / blocked"],
		["validation", "blocked / done"],
	];
	const BOX_W = 340;
	const BOX_H = 46;
	const GAP = 32;
	const PAD = 24;

	const boxes = NODES.map(([name, states], i) => ({
		name,
		states,
		x: PAD,
		y: PAD + i * (BOX_H + GAP),
		w: BOX_W,
		h: BOX_H,
	}));

	let body = "  <!-- each artifact gates the next -->\n";
	for (let i = 0; i < boxes.length - 1; i++) {
		const a = boxes[i];
		const b = boxes[i + 1];
		body += `  <path class="edge" d="M${a.x + a.w / 2},${a.y + a.h} V${b.y}" marker-end="url(#arw)"/>\n`;
	}
	for (const b of boxes) {
		body += `  <rect class="main" x="${b.x}" y="${b.y}" width="${b.w}" height="${b.h}" rx="8"/>\n`;
		body += `  <text class="mono node" x="${b.x + 18}" y="${b.y + b.h / 2 + 5}">${esc(b.name)}</text>\n`;
		body += `  <text class="state" x="${b.x + b.w - 18}" y="${b.y + b.h / 2 + 5}" text-anchor="end">${esc(b.states)}</text>\n`;
	}

	const [file, label] = CAPTION[lang].pipeline;
	const last = boxes[boxes.length - 1];
	return emit({
		file,
		lang,
		label,
		w: BOX_W + PAD * 2,
		h: last.y + BOX_H + PAD,
		body,
		checks: boxes.slice(1).map((b, i) => [b.y > boxes[i].y + BOX_H, `box ${b.name} overlaps the one above it`]),
	});
}

// ── 3. Artifact order, one line ──────────────────────────────────────────────
// docs/Architecture.md, section 3.3. Same order as the pipeline above, shown
// flat because it sits inline in a paragraph.
function artifactOrder(lang) {
	const ITEMS = ["evidence", "command", "manifest", "readme", "context", "validation"];
	const BOX_H = 42;
	const GAP = 30;
	const PAD = 20;
	const CHAR_W = 8.6;
	const PAD_IN = 18;

	const boxes = [];
	let x = PAD;
	for (const name of ITEMS) {
		const w = Math.round(name.length * CHAR_W) + PAD_IN * 2;
		boxes.push({ name, x, y: PAD, w, h: BOX_H });
		x += w + GAP;
	}

	let body = "  <!-- artifacts in dependency order -->\n";
	for (let i = 0; i < boxes.length - 1; i++) {
		const a = boxes[i];
		const b = boxes[i + 1];
		body += `  <path class="edge" d="M${a.x + a.w},${a.y + a.h / 2} H${b.x}" marker-end="url(#arw)"/>\n`;
	}
	for (const b of boxes) {
		body += `  <rect class="card" x="${b.x}" y="${b.y}" width="${b.w}" height="${b.h}" rx="8"/>\n`;
		body += `  <text class="mono node" x="${b.x + b.w / 2}" y="${b.y + b.h / 2 + 5}" text-anchor="middle">${esc(b.name)}</text>\n`;
	}

	const [file, label] = CAPTION[lang].order;
	const last = boxes[boxes.length - 1];
	return emit({
		file,
		lang,
		label,
		w: last.x + last.w + PAD,
		h: BOX_H + PAD * 2,
		body,
		checks: boxes.slice(1).map((b, i) => [b.x > boxes[i].x + boxes[i].w, `pill ${b.name} overlaps the one before it`]),
	});
}

for (const build of [architecture, artifactPipeline, artifactOrder]) {
	for (const lang of ["zh", "en"]) {
		console.log("wrote", build(lang));
	}
}
